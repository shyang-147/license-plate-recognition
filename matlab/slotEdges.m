function edges = slotEdges(n)
%SLOTEDGES 车牌字符的固定槽位边界(按车牌宽归一化)
%
%   edges = SLOTEDGES(7)     % 普通 7 位牌 -> 1x8
%   edges = SLOTEDGES(8)     % 新能源 8 位牌 -> 1x9
%
%   用法: 第 k 个字符占车牌宽度的 [edges(k), edges(k+1)] 这一段。
%   车牌经 correctPlate 拉正后是规范矩形, 字符的相对位置是固定的, 所以可以
%   直接按槽位切 —— 这正是绕开"二值化 + 垂直投影分割"那条链的办法(见
%   README "已知限制": 真实照片上真正的瓶颈是分割, 不是识别)。
%
%   边界怎么来的(第十轮取证, 见 结果记录/第十轮_槽位布局.txt):
%     取 CCPD 中"用真值四角裁片后恰好切对位数"的图, 统计每个槽位字符墨迹
%     外接框的 10% / 90% 分位, 再用相邻墨迹框的中点当槽位边界。这样每个字
%     都落在格子中间、两侧各留半格空隙, 与真实裁切一致。
%     7 位用了 172 张样本; 8 位(新能源)只有 19 张, 尾部 6 格改按等宽放置
%     —— 新能源牌后 6 位字符等宽, 而 19 张样本的墨迹统计噪声比等宽假设更大。
%
%   这不是"近似一下": 槽位切错一格整牌就全错。所以训练数据生成时会给边界
%   加随机抖动(见 slotChars 的 'Jitter'), 让 CNN 对几个像素的偏差不敏感。

switch n
    case 7
        edges = [0.0035 0.1542 0.3002 0.4428 0.5813 0.7114 0.8415 1.0000];
    case 8
        edges = [0.0028 0.1374 0.2895 0.4080 0.5264 0.6449 0.7634 0.8818 1.0000];
    otherwise
        % 没收录的位数(双排牌切错等): 退回等宽, 不硬套 7/8 位的槽位
        edges = linspace(0, 1, n + 1);
end
end